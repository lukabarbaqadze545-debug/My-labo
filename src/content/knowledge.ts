/**
 * Knowledge taught through the Teach Labo panel. Held separately from the
 * bundled corpus so it stays identifiable, and merged at read time so a new
 * entry is usable on the very next message without a rebuild.
 */
let userEntries: KnowledgeEntry[] = [];

let byTopic = new Map<string, KnowledgeEntry[]>();

function reindex(): void {
  byTopic = new Map();
  for (const entry of [...KNOWLEDGE, ...userEntries]) {
    const bucket = byTopic.get(entry.topicId);
    if (bucket) bucket.push(entry);
    else byTopic.set(entry.topicId, [entry]);
  }
}
reindex();

export function setUserKnowledge(entries: readonly KnowledgeEntry[]): void {
  userEntries = [...entries];
  reindex();
}

export function userKnowledgeEntries(): readonly KnowledgeEntry[] {
  return userEntries;
}

export function facetsFor(topicId: string, facet: Facet): KnowledgeEntry[] {
  return (byTopic.get(topicId) ?? []).filter((e) => e.facet === facet);
}

export function hasFacet(topicId: string, facet: Facet): boolean {
  return facetsFor(topicId, facet).length > 0;
}

export function knowledgeForTopic(topicId: string): KnowledgeEntry[] {
  return byTopic.get(topicId) ?? [];
}
