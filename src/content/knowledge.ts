import type { L10n } from './schema';

/**
 * Knowledge facets.
 *
 * Topics are written as articles: whatIs, whyInteresting, keyIdeas, history.
 * A conversation asks for different cuts of the same material — "simpler",
 * "an example", "when does it break" — and none of those map onto an article
 * section. This layer supplies those cuts explicitly.
 *
 * Everything here restates material the library already holds, which is why
 * provenance defaults to `library` with the anchoring topic. Nothing in this
 * file is a new factual claim sourced from outside Luka's Labo.
 */

export type Facet =
  | 'simple'
  | 'example'
  | 'limitation'
  | 'whenToUse'
  | 'why'
  | 'analogy'
  | 'definition'
  | 'compare';

export interface Provenance {
  sourceTitle: string;
  sourceURL?: string;
  sourceType: 'library' | 'encyclopedia' | 'textbook' | 'user' | 'derived';
  retrievedAt?: string;
  confidence: 'high' | 'medium' | 'low';
  notes?: string;
}

export interface KnowledgeEntry {
  id: string;
  topicId: string;
  facet: Facet;
  text: L10n;
  /** 1 = plainest, 3 = most technical. Drives „მარტივად" / „უფრო ღრმად". */
  level?: 1 | 2 | 3;
  source?: Provenance;
}

const lib = (topicId: string): Provenance => ({
  sourceTitle: `ლაბოს თემა: ${topicId}`,
  sourceType: 'library',
  confidence: 'high',
});

/** Terser authoring helper — every entry gets a derived id and library source. */
let seq = 0;
function k(topicId: string, facet: Facet, ka: string, level: 1 | 2 | 3 = 2): KnowledgeEntry {
  seq += 1;
  return { id: `k${seq}_${topicId}_${facet}`, topicId, facet, text: { ka }, level, source: lib(topicId) };
}

